SET NAMES utf8mb4;
CREATE TABLE IF NOT EXISTS admins (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 username VARCHAR(120) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL,
 active TINYINT NOT NULL DEFAULT 1,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS vehicles (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 slug VARCHAR(150) NOT NULL UNIQUE,
 make VARCHAR(80) NOT NULL, model VARCHAR(100) NOT NULL,
 variant VARCHAR(100) DEFAULT NULL, year SMALLINT DEFAULT NULL,
 category ENUM('Hatchback','Sedan','Compact SUV','SUV','Seven Seater') NOT NULL DEFAULT 'SUV',
 transmission ENUM('Manual','Automatic') NOT NULL DEFAULT 'Manual',
 fuel VARCHAR(30) DEFAULT NULL,
 seats TINYINT UNSIGNED NOT NULL DEFAULT 5,
 daily_rate DECIMAL(10,2) DEFAULT NULL, included_km SMALLINT UNSIGNED DEFAULT NULL,
 min_days SMALLINT UNSIGNED NOT NULL DEFAULT 1,
 status ENUM('draft','active','inactive') NOT NULL DEFAULT 'draft',
 approved TINYINT NOT NULL DEFAULT 0, featured TINYINT NOT NULL DEFAULT 0,
 notes TEXT DEFAULT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 INDEX idx_public(status,approved,category,transmission)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS vehicle_images (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY, vehicle_id BIGINT UNSIGNED NOT NULL,
 file_path VARCHAR(300) NOT NULL, alt_text VARCHAR(200) DEFAULT NULL, sort_order INT NOT NULL DEFAULT 0,
 CONSTRAINT fk_image_car FOREIGN KEY(vehicle_id) REFERENCES vehicles(id) ON DELETE CASCADE,
 INDEX(vehicle_id,sort_order)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS vehicle_blocks (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,vehicle_id BIGINT UNSIGNED NOT NULL,
 starts_at DATETIME NOT NULL,ends_at DATETIME NOT NULL,reason VARCHAR(250) DEFAULT NULL,
 FOREIGN KEY(vehicle_id) REFERENCES vehicles(id) ON DELETE CASCADE,INDEX(vehicle_id,starts_at,ends_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS bookings (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 reference VARCHAR(30) NOT NULL UNIQUE,access_hash CHAR(64) NOT NULL,
 vehicle_id BIGINT UNSIGNED NOT NULL,customer_name VARCHAR(100) NOT NULL,
 customer_phone VARCHAR(15) NOT NULL,customer_email VARCHAR(200) DEFAULT NULL,
 pickup_location VARCHAR(100) NOT NULL,return_location VARCHAR(100) NOT NULL,
 pickup_at DATETIME NOT NULL,return_at DATETIME NOT NULL,
 estimated_total DECIMAL(12,2) DEFAULT NULL,estimated_days SMALLINT UNSIGNED NOT NULL,
 status ENUM('pending','confirmed','active','completed','cancelled','rejected') NOT NULL DEFAULT 'pending',
 payment_status ENUM('unpaid','pending_verification','verified','rejected') NOT NULL DEFAULT 'unpaid',
 submitted_utr VARCHAR(80) DEFAULT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(vehicle_id) REFERENCES vehicles(id) ON DELETE RESTRICT,
 INDEX idx_overlaps(vehicle_id,status,pickup_at,return_at),INDEX idx_created(created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS booking_events (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,booking_id BIGINT UNSIGNED NOT NULL,
 actor_admin_id BIGINT UNSIGNED DEFAULT NULL,event VARCHAR(255) NOT NULL,created_at DATETIME NOT NULL,
 FOREIGN KEY(booking_id) REFERENCES bookings(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS enquiries (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(100) NOT NULL,phone VARCHAR(15) NOT NULL,message TEXT NOT NULL,
 created_at DATETIME NOT NULL,INDEX(created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
